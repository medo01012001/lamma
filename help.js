function howtoHtml(id) {
  const g = GAMES[id], h = HOWTO[id];
  if (!g || !h) return '';
  return `<div class="howto"><div class="hhead"><span>${g.icon}</span> كيفاش تلعب <b>${g.title}</b>؟</div>
    <ol>${h.steps.map(s => `<li>${s}</li>`).join('')}</ol>
    <div class="hpts">⭐ <b>النقط:</b> ${h.pts}</div>
    ${h.tip ? `<div class="htip">💡 ${h.tip}</div>` : ''}</div>`;
}

function showHelp(id) {
  if ($('.modal')) return;
  const c = ctx();
  id = id || (GAMES[c.meta.game] ? c.meta.game : c.meta.sel || 'draw');
  const d = document.createElement('div');
  d.className = 'modal';
  d.innerHTML = `<div class="mbox hbox" role="dialog" aria-modal="true">${howtoHtml(id)}
    <div class="mbtns"><button class="btn" id="hok">فهمت 👍</button></div></div>`;
  document.body.appendChild(d);
  const close = () => d.remove();
  $('#hok', d).onclick = close;
  d.onclick = e => { if (e.target === d) close(); };
}
